"""Writes the 1,095 day cells (3 years x 365 days) into s1-zero.html as static SVG rects."""
import re

X0, Y0, CELL, STEP, BLOCK_GAP = 245, 230, 22, 27, 40
rects = []
for b in range(3):
    by = Y0 + b * (7 * STEP + BLOCK_GAP)
    for c in range(53):
        for r in range(7):
            day = c * 7 + r
            if day >= 365:
                continue
            idx = b * 365 + day
            x, y = X0 + c * STEP, by + r * STEP
            if idx == 0:
                continue
            rects.append(f'<rect x="{x}" y="{y}" width="{CELL}" height="{CELL}" rx="5"/>')
first = f'<rect id="s1-c0" x="{X0}" y="{Y0}" width="{CELL}" height="{CELL}" rx="5" fill="#3f3f46"/>'
block = (
    "<!-- <grid:auto> generated by scripts/gen-grid.py: 1,095 day cells, 3 years of 53 x 7 -->\n"
    f'        <g id="s1-cells" fill="#27272a">{"".join(rects)}</g>\n        {first}\n'
    "        <!-- </grid:auto> -->"
)
p = "compositions/s1-zero.html"
s = open(p).read()
s = re.sub(r"<!-- <grid:auto>.*?<!-- </grid:auto> -->", lambda m: block, s, flags=re.S)
open(p, "w").write(s)
print(len(rects) + 1, "cells")
